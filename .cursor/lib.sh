#!/usr/bin/env bash
# Shared helpers for the Transovo AI SMS Cloud Agent environment.
# Sourced by install.sh and start.sh. Never exits the caller directly.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUPABASE_PROJECT="workspace"

log() { echo "[cloud-env] $*"; }

DOCKERD_LOG="/var/log/cloud-env-dockerd.log"

# Start the Docker daemon inside the Cloud Agent VM (nested Docker).
# Idempotent: no-op if the daemon already answers.
start_docker() {
  if sudo docker info >/dev/null 2>&1; then
    log "docker already running"
    sudo chmod 666 /var/run/docker.sock 2>/dev/null || true
    return 0
  fi

  # Bridged container-to-container traffic must bypass host netfilter, otherwise
  # inter-container connections (PostgREST -> Postgres) time out in this VM.
  sudo modprobe br_netfilter 2>/dev/null || true
  sudo sysctl -w net.bridge.bridge-nf-call-iptables=0 >/dev/null 2>&1 || true
  sudo sysctl -w net.bridge.bridge-nf-call-ip6tables=0 >/dev/null 2>&1 || true

  log "starting dockerd (fuse-overlayfs), logging to ${DOCKERD_LOG}"
  # Run as root and detach so dockerd outlives this script. The log lives under
  # /var/log (root-writable) to avoid /tmp ownership surprises across snapshots.
  sudo rm -f "$DOCKERD_LOG" 2>/dev/null || true
  sudo sh -c "setsid dockerd --storage-driver=fuse-overlayfs >'$DOCKERD_LOG' 2>&1 </dev/null &"

  for _ in $(seq 1 40); do
    if sudo docker info >/dev/null 2>&1; then
      sudo chmod 666 /var/run/docker.sock 2>/dev/null || true
      log "dockerd is up"
      return 0
    fi
    sleep 1
  done
  log "ERROR: dockerd did not become ready"
  sudo tail -20 "$DOCKERD_LOG" 2>/dev/null || true
  return 1
}

# Bring up the local Supabase stack (db + kong + postgrest per config.toml).
start_supabase() {
  cd "$REPO_ROOT"
  if docker ps --format '{{.Names}}' 2>/dev/null | grep -q "supabase_kong_${SUPABASE_PROJECT}"; then
    log "supabase stack already running"
    return 0
  fi
  log "starting supabase local stack (first run pulls images)"
  supabase start
}

# Write .env pointing the app at the local Supabase stack.
write_env() {
  cd "$REPO_ROOT"
  local kong_yml keys anon service
  kong_yml="$(docker exec "supabase_kong_${SUPABASE_PROJECT}" sh -c 'find / -name kong.yml 2>/dev/null | head -1 | xargs cat' 2>/dev/null || true)"
  keys="$(printf '%s' "$kong_yml" | node "$REPO_ROOT/.cursor/extract-supabase-keys.mjs")"
  anon="$(printf '%s\n' "$keys" | sed -n 's/^ANON_KEY=//p')"
  service="$(printf '%s\n' "$keys" | sed -n 's/^SERVICE_ROLE_KEY=//p')"
  if [ -z "$anon" ] || [ -z "$service" ]; then
    log "ERROR: could not resolve Supabase keys"
    return 1
  fi

  cat > "$REPO_ROOT/.env" <<EOF
# Auto-generated by .cursor/start.sh — local Supabase dev stack. Do not commit.
APP_URL="http://localhost:3000"
NEXT_PUBLIC_APP_URL="http://localhost:3000"
NEXT_PUBLIC_SUPABASE_URL="http://127.0.0.1:54321"
NEXT_PUBLIC_SUPABASE_ANON_KEY="${anon}"
SUPABASE_SERVICE_ROLE_KEY="${service}"
DATABASE_URL="postgresql://postgres:postgres@127.0.0.1:54322/postgres"
MESSAGING_PROVIDER="mock"
EOF
  log ".env written"
}

# Apply the Prisma schema and seed the demo workspace (both idempotent).
apply_schema_and_seed() {
  cd "$REPO_ROOT"
  set -a; . "$REPO_ROOT/.env"; set +a
  log "prisma db push"
  npm run db:push
  docker exec "supabase_db_${SUPABASE_PROJECT}" psql -U postgres -d postgres \
    -c "NOTIFY pgrst, 'reload schema';" >/dev/null 2>&1 || true
  sleep 2
  log "seeding demo workspace"
  npm run db:seed
}

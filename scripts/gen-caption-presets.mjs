#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const jsonPath = path.join(root, 'new-app/lib/clips/caption-presets.json')
const presets = JSON.parse(fs.readFileSync(jsonPath, 'utf8'))

const tsPath = path.join(root, 'new-app/lib/clips/caption-presets.ts')
const pyPath = path.join(root, 'worker/clips_worker/caption_presets.py')

const header = '// DO NOT EDIT — generated by scripts/gen-caption-presets.mjs\n'

const ts = `${header}
export type CaptionPreset = {
  slug: string
  name: string
  font: string
  weight: number
  case: 'upper' | 'sentence'
  wordsPerLine: number
  sizePct: number
  position: 'bottom' | 'middle' | 'top'
  marginVPct: number
  primary: string
  active: string
  activeB: string
  outline: string
  outlineW: number
  shadow: number
  box: null | { color: string; padX: number; padY: number; radius: number }
  animation: 'none' | 'pop' | 'bounce' | 'slideup' | 'typewriter' | 'karaoke' | 'glow'
  emphasisScale: number
}

export const CAPTION_PRESETS: CaptionPreset[] = ${JSON.stringify(presets, null, 2)} as CaptionPreset[]

export function presetSlugToId(slug: string): string {
  return slug.replace(/-/g, '_')
}

export const bySlug: Record<string, CaptionPreset> = Object.fromEntries(
  CAPTION_PRESETS.map((p) => [p.slug, p]),
)

export const byId: Record<string, CaptionPreset> = Object.fromEntries(
  CAPTION_PRESETS.map((p) => [presetSlugToId(p.slug), p]),
)

export function resolvePreset(presetId?: string | null): CaptionPreset {
  const id = presetId?.trim() || 'bold_pop'
  return byId[id] ?? byId.bold_pop ?? CAPTION_PRESETS[0]
}
`

const pyPresets = Object.fromEntries(presets.map((p) => [p.slug.replace(/-/g, '_'), p]))
const pyJson = JSON.stringify(pyPresets, null, 2).replace(/\bnull\b/g, 'None')

const py = `"""DO NOT EDIT — generated by scripts/gen-caption-presets.mjs"""
from __future__ import annotations

PRESETS: dict[str, dict] = ${pyJson}

def resolve_preset(preset_id: str | None) -> dict:
    key = (preset_id or "bold_pop").replace("-", "_")
    return PRESETS.get(key, PRESETS["bold_pop"])


def apply_preset_to_ass(ass_path, preset_id: str) -> None:
    """Legacy hook after speakercrop ASS; no-op when preset is bold_pop."""
    if (preset_id or "bold_pop").replace("-", "_") == "bold_pop":
        return
`

fs.writeFileSync(tsPath, ts)
fs.writeFileSync(pyPath, py)
console.log('Wrote', tsPath, pyPath)

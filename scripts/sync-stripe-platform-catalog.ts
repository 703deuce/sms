#!/usr/bin/env node
/**
 * Idempotent Stripe platform catalog sync.
 * Run: npx tsx scripts/sync-stripe-platform-catalog.ts [--dry-run] [--write-ids]
 */
import { existsSync, writeFileSync } from "fs";
import { resolve } from "path";
import dotenv from "dotenv";
import { syncPlatformBillingCatalogToStripe } from "../src/lib/products/platform-billing-catalog-sync.ts";

for (const file of [".env.local", ".env"]) {
  const path = resolve(process.cwd(), file);
  if (existsSync(path)) dotenv.config({ path });
}

const dryRun = process.argv.includes("--dry-run");
const writeIds = process.argv.includes("--write-ids");

function catalogToTs(mode: "live" | "test", catalog: ReturnType<typeof Object>) {
  return `/** Auto-generated by scripts/sync-stripe-platform-catalog.ts — ${mode} mode */\nimport type { PlatformCatalogIds } from "./platform-billing-catalog-definitions";\n\nexport const PLATFORM_BILLING_CATALOG_${mode.toUpperCase()}: PlatformCatalogIds = ${JSON.stringify(catalog, null, 2)} as const;\n`;
}

async function main() {
  const result = await syncPlatformBillingCatalogToStripe({ dryRun });
  console.log(
    JSON.stringify(
      {
        ok: true,
        mode: result.mode,
        created: result.created,
        reused: result.reused,
        warnings: result.warnings,
        catalog: result.catalog,
      },
      null,
      2,
    ),
  );

  if (writeIds && !dryRun) {
    const file =
      result.mode === "test"
        ? "src/lib/products/platform-billing-catalog-ids-test.ts"
        : "src/lib/products/platform-billing-catalog-ids-live.ts";
    writeFileSync(resolve(process.cwd(), file), catalogToTs(result.mode, result.catalog));
    console.log(`Wrote ${file}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

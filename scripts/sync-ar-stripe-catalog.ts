#!/usr/bin/env node
/**
 * Idempotent Stripe catalog for Appointment Reminders (Starter / Growth / Business).
 * Run: npx tsx scripts/sync-ar-stripe-catalog.ts [--dry-run] [--write-ids]
 */
import { existsSync, writeFileSync } from "fs";
import { resolve } from "path";
import dotenv from "dotenv";
import Stripe from "stripe";
import {
  AR_PAID_PLAN_KEYS,
  arPlanDefinition,
  type ArPlanKey,
} from "../src/lib/appointment-reminders/commercial/ar-plan-catalog.ts";
import type { ArStripeCatalog } from "../src/lib/appointment-reminders/commercial/ar-stripe-catalog.ts";

for (const file of [".env.local", ".env"]) {
  const p = resolve(process.cwd(), file);
  if (existsSync(p)) dotenv.config({ path: p });
}

const dryRun = process.argv.includes("--dry-run");
const writeIds = process.argv.includes("--write-ids");

function stripeMode(): "test" | "live" {
  const key = process.env.STRIPE_SECRET_KEY?.trim() || "";
  return key.startsWith("sk_test_") ? "test" : "live";
}

async function listProducts(stripe: Stripe): Promise<Stripe.Product[]> {
  const out: Stripe.Product[] = [];
  let startingAfter: string | undefined;
  for (;;) {
    const page = await stripe.products.list({ limit: 100, starting_after: startingAfter });
    out.push(...page.data);
    if (!page.has_more || !page.data.length) break;
    startingAfter = page.data[page.data.length - 1]?.id;
  }
  return out;
}

async function listPrices(stripe: Stripe, productId: string): Promise<Stripe.Price[]> {
  const out: Stripe.Price[] = [];
  let startingAfter: string | undefined;
  for (;;) {
    const page = await stripe.prices.list({
      product: productId,
      active: true,
      limit: 100,
      starting_after: startingAfter,
    });
    out.push(...page.data);
    if (!page.has_more || !page.data.length) break;
    startingAfter = page.data[page.data.length - 1]?.id;
  }
  return out;
}

async function main() {
  const key = process.env.STRIPE_SECRET_KEY?.trim();
  if (!key) {
    console.error("STRIPE_SECRET_KEY not set — cannot sync AR Stripe catalog.");
    process.exit(1);
  }
  const stripe = new Stripe(key);
  const mode = stripeMode();
  const products = await listProducts(stripe);

  const catalog: ArStripeCatalog = {
    productIds: { free: null, starter: null, growth: null, business: null },
    priceIds: { free: null, starter: null, growth: null, business: null },
  };

  const audit = { created: [] as string[], reused: [] as string[] };

  for (const plan of AR_PAID_PLAN_KEYS) {
    const def = arPlanDefinition(plan);
    const transovoProduct = `appointment_reminders_${plan}`;
    let product = products.find(
      (p) =>
        !p.deleted &&
        p.metadata?.product_family === "appointment_reminders" &&
        p.metadata?.plan_key === plan,
    );
    if (!product && !dryRun) {
      product = await stripe.products.create({
        name: `Transovo Appointment Reminders — ${def.displayName}`,
        description: `Appointment Reminders ${def.displayName} plan`,
        metadata: {
          product_family: "appointment_reminders",
          plan_key: plan,
          billing_interval: "month",
          transovo_product: transovoProduct,
        },
      });
      audit.created.push(`product:${plan}:${product.id}`);
    } else if (product) {
      audit.reused.push(`product:${plan}:${product.id}`);
    }
    if (!product) {
      console.warn(`dry-run: would create product for ${plan}`);
      continue;
    }
    catalog.productIds[plan] = product.id;

    const prices = await listPrices(stripe, product.id);
    let price = prices.find(
      (p) =>
        p.currency === "usd" &&
        p.recurring?.interval === "month" &&
        p.unit_amount === def.monthlyPriceCents &&
        p.metadata?.plan_key === plan,
    );
    if (!price && !dryRun) {
      price = await stripe.prices.create({
        product: product.id,
        currency: "usd",
        unit_amount: def.monthlyPriceCents,
        recurring: { interval: "month" },
        metadata: {
          product_family: "appointment_reminders",
          plan_key: plan,
          billing_interval: "month",
        },
      });
      audit.created.push(`price:${plan}:${price.id}`);
    } else if (price) {
      audit.reused.push(`price:${plan}:${price.id}`);
    }
    if (price) catalog.priceIds[plan] = price.id;
  }

  console.log(JSON.stringify({ ok: true, mode, audit, catalog }, null, 2));

  if (writeIds && !dryRun) {
    const file =
      mode === "test"
        ? "src/lib/appointment-reminders/commercial/ar-stripe-catalog-ids-test.ts"
        : "src/lib/appointment-reminders/commercial/ar-stripe-catalog-ids-live.ts";
    const body = `/** Auto-generated by scripts/sync-ar-stripe-catalog.ts — ${mode} */\nimport type { ArStripeCatalog } from "@/lib/appointment-reminders/commercial/ar-stripe-catalog";\n\nexport const AR_STRIPE_CATALOG_${mode.toUpperCase()}: ArStripeCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`;
    writeFileSync(resolve(process.cwd(), file), body);
    console.log(`Wrote ${file}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

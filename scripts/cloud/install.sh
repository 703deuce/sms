#!/usr/bin/env bash
# Cloud Agent `install` phase — idempotent, durable one-time setup.
#
# Prepares everything that can be baked into the environment snapshot:
#   system packages, node_modules, Prisma client, the local Postgres cluster
#   + Supabase roles, the applied schema, a demo seed, and a local .env.
# Per-boot daemon startup lives in start.sh instead.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"
ROOT="$(repo_root)"
cd "$ROOT"

# Always target the local stack, even if hosted Supabase secrets are injected.
use_local_env

echo "==> [1/7] System packages (postgresql, nginx, xz, curl)"
need_pkgs=()
command -v nginx >/dev/null 2>&1 || need_pkgs+=(nginx-light)
ls /usr/lib/postgresql/*/bin/initdb >/dev/null 2>&1 || need_pkgs+=(postgresql postgresql-contrib)
command -v xz >/dev/null 2>&1 || need_pkgs+=(xz-utils)
command -v curl >/dev/null 2>&1 || need_pkgs+=(curl)
if [ "${#need_pkgs[@]}" -gt 0 ]; then
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${need_pkgs[@]}"
fi

echo "==> [2/7] PostgREST binary"
if ! command -v postgrest >/dev/null 2>&1; then
  PGREST_VER="v12.2.12"
  tmp="$(mktemp -d)"
  curl -fsSL -o "$tmp/postgrest.tar.xz" \
    "https://github.com/PostgREST/postgrest/releases/download/${PGREST_VER}/postgrest-${PGREST_VER}-linux-static-x86-64.tar.xz"
  tar -C "$tmp" -xf "$tmp/postgrest.tar.xz"
  sudo install -m 0755 "$tmp/postgrest" /usr/local/bin/postgrest
  rm -rf "$tmp"
fi
postgrest --version || true

echo "==> [3/7] npm dependencies + Prisma client"
if [ -f package-lock.json ]; then npm ci; else npm install; fi
npm run db:generate

echo "==> [4/7] Local Postgres cluster + Supabase roles"
mkdir -p "$TRANSOVO_HOME/sock"
if [ ! -f "$PGDATA/PG_VERSION" ]; then
  mkdir -p "$PGDATA"
  printf 'postgres' > "$TRANSOVO_HOME/.pgpw"
  pg initdb -D "$PGDATA" -U postgres --auth=trust --pwfile="$TRANSOVO_HOME/.pgpw" -E UTF8
  rm -f "$TRANSOVO_HOME/.pgpw"
  {
    echo "listen_addresses = '127.0.0.1'"
    echo "port = $PGPORT"
    echo "unix_socket_directories = '$TRANSOVO_HOME/sock'"
  } >> "$PGDATA/postgresql.conf"
fi
if ! pg_running; then
  pg pg_ctl -D "$PGDATA" -l "$TRANSOVO_HOME/pg.log" start
fi
wait_for_pg
psql_super <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN NOINHERIT; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated NOLOGIN NOINHERIT; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='authenticator') THEN CREATE ROLE authenticator LOGIN NOINHERIT PASSWORD 'postgres'; END IF;
END\$\$;
GRANT anon, authenticated, service_role TO authenticator;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO anon, authenticated;
SQL

echo "==> [5/7] Local .env"
if [ ! -f "$ROOT/.env" ]; then
  {
    printf '# Local Cloud Agent development environment (generated by scripts/cloud/install.sh).\n'
    printf 'APP_URL="%s"\n' "$LOCAL_APP_URL"                      # pragma: allowlist secret
    printf 'NEXT_PUBLIC_APP_URL="%s"\n' "$LOCAL_APP_URL"          # pragma: allowlist secret
    printf 'DATABASE_URL="%s"\n' "$LOCAL_DATABASE_URL"            # pragma: allowlist secret
    printf 'NEXT_PUBLIC_SUPABASE_URL="%s"\n' "$LOCAL_SUPABASE_URL"
    printf 'NEXT_PUBLIC_SUPABASE_ANON_KEY="%s"\n' "$ANON_KEY"
    printf 'SUPABASE_SERVICE_ROLE_KEY="%s"\n' "$SERVICE_ROLE_KEY"
    printf 'MESSAGING_PROVIDER=mock\n'
    printf 'CRON_SECRET="%s"\n' "$LOCAL_CRON_SECRET"              # pragma: allowlist secret
  } > "$ROOT/.env"
  echo "    wrote $ROOT/.env"
else
  echo "    .env already present — leaving it untouched"
fi

echo "==> [6/7] Apply Prisma schema + grant table privileges"
npm run db:push
psql_super <<'SQL'
GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO anon, authenticated;
NOTIFY pgrst, 'reload schema';
SQL

echo "==> [7/7] Seed demo workspace"
# prisma/seed.ts generates a fresh id each run and upserts on the primary key,
# so re-seeding collides on the unique email. Guard it to stay idempotent.
seeded="$(psql_super -tAc "SELECT 1 FROM \"User\" WHERE email = 'alex@harborhome.co' LIMIT 1" || true)"
if [ "$seeded" = "1" ]; then
  echo "    demo workspace already seeded — skipping"
else
  npm run db:seed
fi

echo "==> install complete. Login: alex@harborhome.co / demo1234"

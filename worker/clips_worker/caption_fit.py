"""E3fix: width-aware caption lines for burned-in ASS (libass WrapStyle 2 never wraps).

The editor preview lays caption words out with CSS flex-wrap, so a long chunk wraps onto a
second line there. The export ASS uses ``WrapStyle: 2`` (no automatic wrapping), so the same
chunk was drawn as one centred line wider than the frame and clipped at both edges
("Energy, capital, whateve"). ``fit_caption_line`` measures the chunk with the bundled font
advance tables (caption_font_metrics.json — byte-identical to new-app/lib/clips/caption-fit-metrics.json,
generated by worker/scripts/gen_caption_fit_metrics.py) and returns explicit
``\\N`` break points plus, only when a single word is still too wide, a uniform shrink.
"""
from __future__ import annotations

import json
import math
import re
from functools import lru_cache
from pathlib import Path

_METRICS_PATH = Path(__file__).resolve().parent / "caption_font_metrics.json"
_EMOJI_ADV_EM = 1.25
# E3fix2: every caption font the export burns with is bundled (Poppins, Anton, Montserrat and
# the T6 set). A name outside that list measures as Montserrat Black so it wraps early, not clips.
_FALLBACK_FONT = "Montserrat Black"
_FONT_ALIASES = {
    "Montserrat": "Montserrat Black",
    "Poppins": "Poppins ExtraBold",
    "Lato Black": "Lato",  # EP1 canonical ASS name → metrics row
}
# Kerning is ignored; keep a small slack so a measured "fits" really fits.
_SLACK = 0.97
_SCALE_TAG_RE = re.compile(r"\\fsc([xy])(\d+(?:\.\d+)?)")


# Reference frame for line breaking: 1080 px on the short side (the 1080p export), same aspect.
FIT_REF_SHORT_PX = 1080
# Safe width = PlayRes width minus the ASS side margins (mirror of captions_ass.margin_lr_px).
_SAFE_MARGIN_MIN_PX = 54
_SAFE_MARGIN_FRAC = 0.05


def round_half_up(x: float) -> int:
    """Deterministic rounding shared with new-app/lib/clips/caption-fit.ts (Math.round)."""
    return int(math.floor(float(x) + 0.5))


def fit_reference_frame(play_w: int, play_h: int) -> tuple[int, int, float]:
    """(ref_w, ref_h, k): the export frame scaled so its short side is FIT_REF_SHORT_PX."""
    short = max(1, min(int(play_w), int(play_h)))
    k = FIT_REF_SHORT_PX / short
    return round_half_up(play_w * k), round_half_up(play_h * k), k


def caption_safe_width_px(play_w: int) -> int:
    margin = max(_SAFE_MARGIN_MIN_PX, round_half_up(play_w * _SAFE_MARGIN_FRAC))
    return max(1, int(play_w) - 2 * margin)


@lru_cache(maxsize=1)
def _all_metrics() -> dict:
    try:
        return json.loads(_METRICS_PATH.read_text())
    except (OSError, ValueError):
        return {}


def register_font_metrics(name: str, metrics: dict) -> bool:
    """G3b: add a workspace (uploaded) font's metrics row — same shape as caption_font_metrics.json
    ({unitsPerEm, defaultAdv, assEmPerFontsize, adv}); the web parses it at upload time."""
    try:
        row = {
            "unitsPerEm": float(metrics["unitsPerEm"]),
            "defaultAdv": float(metrics["defaultAdv"]),
            "assEmPerFontsize": float(metrics["assEmPerFontsize"]),
            "adv": {str(k): float(v) for k, v in dict(metrics.get("adv") or {}).items()},
        }
    except (KeyError, TypeError, ValueError):
        return False
    if not name or row["unitsPerEm"] <= 0 or row["assEmPerFontsize"] <= 0:
        return False
    _all_metrics()[str(name)] = row
    return True


def _metrics(font: str | None) -> dict | None:
    allm = _all_metrics()
    name = _FONT_ALIASES.get(str(font or ""), str(font or ""))
    return allm.get(name) or allm.get(_FALLBACK_FONT)


def _is_emoji(cp: int) -> bool:
    return 0x1F300 <= cp <= 0x1FAFF or 0x2600 <= cp <= 0x27BF


def text_width_px(text: str, font: str | None, fontsize: float) -> float:
    """Rendered advance width of ``text`` in PlayRes px at ASS ``Fontsize`` (no kerning)."""
    m = _metrics(font)
    if not m:
        return len(text) * float(fontsize) * 0.62
    upm = float(m["unitsPerEm"])
    adv = m["adv"]
    default = float(m["defaultAdv"])
    units = 0.0
    for ch in text:
        cp = ord(ch)
        units += _EMOJI_ADV_EM * upm if _is_emoji(cp) else float(adv.get(str(cp), default))
    return units / upm * float(fontsize) * float(m["assEmPerFontsize"])


def _rebalance_caption_breaks(word_count: int, breaks: list[int]) -> list[int]:
    if word_count < 3 or not breaks:
        return breaks
    br = list(breaks)
    while br:
        last = br[-1]
        if word_count - last != 1 or last <= 1:
            break
        br[-1] = last - 1
    if br and br[0] == 1:
        return []
    return br


def fit_caption_line(
    words: list[str],
    *,
    font: str | None,
    fontsize: float,
    max_width_px: float,
    peak_scale: float = 1.0,
    pad_px: float = 0.0,
    max_lines: int = 2,
) -> tuple[list[int], float]:
    """Return ``(breaks, scale)`` for one caption chunk.

    ``breaks`` are word indexes that start a new line (``\\N`` before them). ``scale`` is 1.0
    unless the widest resulting line still exceeds ``max_width_px``; then it is the uniform
    factor that makes it fit. ``peak_scale`` covers pop / emphasis \\fscx growth; ``pad_px``
    covers outline / box padding on both sides.
    """
    if not words or max_width_px <= 0 or fontsize <= 0:
        return [], 1.0
    budget = max(1.0, float(max_width_px) * _SLACK - 2.0 * float(pad_px))
    peak = max(1.0, float(peak_scale))
    space = text_width_px(" ", font, fontsize)

    def w(i: int) -> float:
        return text_width_px(words[i], font, fontsize) * peak

    full = sum(w(i) for i in range(len(words))) + space * peak * (len(words) - 1)
    if full <= budget:
        return [], 1.0

    breaks: list[int] = []
    line_w = 0.0
    widths: list[float] = []
    for i in range(len(words)):
        wi = w(i)
        if i == 0:
            line_w = wi
            continue
        trial = line_w + space * peak + wi
        if trial > budget and len(breaks) + 1 < max_lines:
            breaks.append(i)
            widths.append(line_w)
            line_w = wi
        else:
            line_w = trial
    widths.append(line_w)
    balanced = _rebalance_caption_breaks(len(words), breaks)
    if balanced != breaks:
        breaks = balanced
        widths = []
        lw = 0.0
        brk = set(breaks)
        for i in range(len(words)):
            wi = w(i)
            if i == 0:
                lw = wi
                continue
            if i in brk:
                widths.append(lw)
                lw = wi
            else:
                lw += space * peak + wi
        widths.append(lw)
    widest = max(widths)
    scale = 1.0 if widest <= budget else max(0.4, budget / widest)
    return breaks, math.floor(scale * 1000 + 0.5) / 1000


def join_caption_parts(parts: list[str], breaks: list[int]) -> str:
    """Join per-word ASS fragments with spaces, ``\\N`` before each break index."""
    if not breaks:
        return " ".join(parts)
    out = ""
    brk = set(breaks)
    for i, p in enumerate(parts):
        if i == 0:
            out = p
        elif i in brk:
            out += "\\N" + p
        else:
            out += " " + p
    return out


def apply_line_scale(text: str, scale: float) -> str:
    """Uniformly shrink one ASS line: base \\fscx/\\fscy prefix and every explicit scale tag."""
    if scale >= 0.999:
        return text

    def _mul(m: re.Match) -> str:
        return f"\\fsc{m.group(1)}{round_half_up(float(m.group(2)) * scale)}"

    pct = round_half_up(100 * scale)
    return f"{{\\fscx{pct}\\fscy{pct}}}" + _SCALE_TAG_RE.sub(_mul, text)

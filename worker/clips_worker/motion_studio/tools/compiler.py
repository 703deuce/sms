"""Deterministic compiler: versioned scene specification -> motion_core build_scene() source.

The output is trusted compiler code, not model-written code. It is still linted and
executed in the existing sandbox so rendering, word sync, handoffs and the editor
keep working.
"""
from __future__ import annotations

import json
from typing import Any

from clips_worker.motion_studio.tools.spec import duration_s, frames_to_s
from clips_worker.motion_studio.tools.validate import validate_spec

SKIN = {
    "physical_print": "print",
    "print": "print",
    "framed": "print",
    "glass": "glass",
    "tv": "tv",
    "screen": "tv",
    "filmstrip": "filmstrip",
    "plain": "plain",
    "full_bleed": "plain",
    "footage": "plain",
    "clip": "plain",
}



def _series_points(data):
    pts, xs, ys = [], [], []
    for i, row in enumerate(data or []):
        if isinstance(row, (int, float)):
            x, y = float(i), float(row)
        elif isinstance(row, (list, tuple)) and len(row) >= 2:
            x, y = float(row[0]) if isinstance(row[0], (int, float)) else float(i), float(row[1] if isinstance(row[1], (int, float)) else 0)
        elif isinstance(row, dict):
            y = float(row.get("y", row.get("value", row.get("v", 0))) or 0)
            raw_x = row.get("x", row.get("label", i))
            x = float(raw_x) if isinstance(raw_x, (int, float)) else float(i)
        else:
            continue
        pts.append((x, y))
        xs.append(x)
        ys.append(y)
    return pts, xs, ys


class CompileError(ValueError):
    def __init__(self, problems: list[dict[str, str]]):
        super().__init__("; ".join(p.get("message") or str(p) for p in problems))
        self.problems = problems


def compile_spec(spec: dict[str, Any], *, catalog_ids: list[str] | None = None) -> str:
    """Compile a validated specification into build_scene(ctx) Python source."""
    problems = validate_spec(spec, catalog_ids=catalog_ids)
    if problems:
        raise CompileError(problems)
    lines: list[str] = [
        "# Generated by the Motion Studio scene-spec compiler. Do not edit by hand.",
        f"# scene {spec.get('sceneId')} spec {spec.get('version')} engine {spec.get('engineSha', '')[:7]}",
        "from motion_core import *",
        "",
        "def _anchor(ctx, entrance, default=0.1):",
        "    if entrance is None:",
        "        return default",
        "    if isinstance(entrance, (int, float)):",
        "        return float(entrance)",
        "    word = None",
        "    if isinstance(entrance, str):",
        "        word = entrance",
        "    elif isinstance(entrance, dict):",
        "        word = entrance.get('anchorWordId') or entrance.get('wordId')",
        "        if 'line' in entrance and 'word' in entrance:",
        "            return ctx.W(entrance['line'], entrance['word'], int(entrance.get('nth') or 0), end=bool(entrance.get('end')))",
        "        if 't' in entrance:",
        "            return float(entrance['t'])",
        "    if word:",
        "        rec = None",
        "        words = ctx.words if hasattr(ctx, 'words') and ctx.words else []",
        "        if hasattr(ctx, 'word_by_id') and ctx.word_by_id:",
        "            rec = ctx.word_by_id.get(word)",
        "        for w in words:",
        "            if isinstance(w, dict) and w.get('id') == word:",
        "                rec = w",
        "                break",
        "        if rec:",
        "            return float(rec.get('end' if (isinstance(entrance, dict) and entrance.get('end')) else 'start') or rec.get('t') or default)",
        "    return default",
        "",
        "def build_scene(ctx):",
        "    film = ctx.film()",
        "    ink = ctx.rgb('ink')",
        "    accent = ctx.rgb('accent')",
        "    bg = ctx.rgb('bg')",
        "    muted = ctx.rgb('muted')",
    ]

    # Environments become backdrop primitives, never a WORLD_TYPES template.
    for eid, env in (spec.get("environments") or {}).items():
        brief = (env.get("brief") or "").replace("\\", "\\\\").replace('"', '\\"')[:120]
        lines.append(f"    # environment {eid}: {brief}")
        backdrop = env.get("backdrop") or {}
        kind = (backdrop.get("kind") or "").lower()
        size = env.get("size") or {}
        w = int(size.get("width") or 3840)
        h = int(size.get("height") or 2160)
        x, y = -w / 2, -h / 2
        if kind == "grid":
            lines.append("    film.add(GridField())")
        elif kind in ("texture", "grain", "noise"):
            lines.append("    film.add(NoiseTexture())")
        else:
            # Gradient or flat field using official palette colors already bound above.
            lines.append("    film.add(GradientField([bg, muted], center=(0, 0)))")

    # Media, graphics, primitives, typography, effects, extensions.
    for oid, obj in (spec.get("objects") or {}).items():
        kind = obj.get("kind")
        if kind == "media":
            lines.extend(_emit_media(spec, oid, obj))
        elif kind == "graphic":
            lines.extend(_emit_graphic(spec, oid, obj))
        elif kind == "path":
            lines.extend(_emit_path(spec, oid, obj))
        elif kind == "primitive":
            lines.extend(_emit_primitive(spec, oid, obj))
        elif kind == "effect":
            lines.extend(_emit_effect(spec, oid, obj))
        elif kind == "extension":
            lines.extend(_emit_extension(spec, oid, obj))
        elif kind == "group":
            lines.append(f"    # layout group {oid}: {obj.get('memberIds')}")

    for tid, typo in (spec.get("typography") or {}).items():
        lines.extend(_emit_type(spec, tid, typo))

    for sid, snd in (spec.get("sound") or {}).items():
        if snd.get("role") in ("cue", "effect") and snd.get("cue"):
            texpr = _time_expr(spec, snd)
            gain = float(snd.get("gain") or 1.0)
            cue = str(snd["cue"]).replace("'", "")
            lines.append(f"    film.cue('{cue}', {texpr}, {gain})")

    cam_moves = list((spec.get("camera") or {}).values())
    if not cam_moves:
        dur = duration_s(spec)
        end = "ctx.duration" if dur is None else f"{dur:.4f}"
        lines.append("    film.cam(0, 0, 0, 0.4)")
        lines.append(f"    film.cam({end}, 0, 0, 0.4)")
    else:
        cam_moves = sorted(cam_moves, key=lambda c: int(c.get("startFrame") or 0))
        for cam in cam_moves:
            lines.extend(_emit_camera(spec, cam))
        # Guarantee a final key at the scene end if the last move stops early.
        last = cam_moves[-1]
        dur = duration_s(spec)
        if dur is not None and frames_to_s(spec, last.get("endFrame") or 0) < dur - 1e-3:
            pose = last.get("to") or last.get("from") or {"x": 0, "y": 0, "zoom": 0.4, "rot": 0}
            lines.append(
                f"    film.cam({dur:.4f}, {float(pose['x'])}, {float(pose['y'])}, {float(pose['zoom'])}, {float(pose.get('rot') or 0)})"
            )

    lines.append("    return film")
    lines.append("")
    return "\n".join(lines)


def _entrance_expr(obj: dict) -> str:
    entrance = obj.get("entrance") or {}
    return f"_anchor(ctx, {repr(entrance)})"


def _time_expr(spec: dict, obj: dict) -> str:
    if obj.get("anchorWordId"):
        return f"_anchor(ctx, {{'anchorWordId': {obj['anchorWordId']!r}}})"
    if obj.get("startFrame") is not None:
        return f"{frames_to_s(spec, obj['startFrame']):.4f}"
    return "0.1"


def _xy(obj: dict) -> tuple[float, float]:
    pos = obj.get("position") or {}
    return float(pos.get("x") or 0), float(pos.get("y") or 0)


def _emit_media(spec: dict, oid: str, obj: dict) -> list[str]:
    x, y = _xy(obj)
    w = obj.get("width") or 1600
    rot = obj.get("rotation") or 0
    skin = SKIN.get(obj.get("presentation") or "physical_print", "print")
    title = (obj.get("title") or "").replace("\\", "\\\\").replace('"', '\\"')
    label = (obj.get("label") or "").replace("\\", "\\\\").replace('"', '\\"')
    crop = obj.get("crop")
    crop_arg = f", crop={repr(tuple(crop))}" if crop else ""
    key = obj["assetId"]
    return [
        f"    film.add(PhotoFrame({key!r}, {x}, {y}, {w}, rot={rot}, t_in={_entrance_expr(obj)}, "
        f"skin={skin!r}, title={title!r}, label={label!r}, z={int(obj.get('z') or 20)}{crop_arg}))  # {oid}",
    ]


def _emit_graphic(spec: dict, oid: str, obj: dict) -> list[str]:
    x, y = _xy(obj)
    kind = obj.get("graphicKind")
    t_in = _entrance_expr(obj)
    title = (obj.get("title") or "").replace("\\", "\\\\").replace('"', '\\"')
    if kind == "callout":
        return [f"    film.add(Callout({title or oid!r}, {x}, {y}, {t_in}))  # {oid}"]
    if kind == "counter":
        data = obj.get("data") or 0
        target = data if isinstance(data, (int, float)) else 0
        # RollingNumber(x, y, size, v0, v1, t_in, t_land, ...)
        return [f"    film.add(RollingNumber({x}, {y}, 120, 0, {target}, {t_in}, {t_in} + 0.8, caption={title!r}))  # {oid}"]
    if kind == "stamp":
        return [f"    film.add(Stamp({title or 'OK'!r}, {x}, {y}, t_in={t_in}))  # {oid}"]
    if kind == "pin":
        return [f"    film.add(MapPin({x}, {y}, label={title!r}, t_in={t_in}))  # {oid}"]
    if kind in ("chart_line", "chart_bar"):
        pts, xs, ys = _series_points(obj.get("data") or [])
        t0 = t_in
        t1 = f"({t_in}) + 0.8"
        if kind == "chart_line":
            return [f"    film.add(LineSeries({pts!r}, {t0}, {t1}, rgb=accent))  # {oid}"]
        w = obj.get("width") or 80
        base_y = y
        return [f"    film.add(BarSeries({xs!r}, {ys!r}, {base_y}, {w}, {t0}, labels=None, rgb=accent))  # {oid}"]
    if kind in ("map", "route"):
        path = obj.get("path") or obj.get("places") or []
        if kind == "route" or path:
            pts = []
            for p in path:
                if isinstance(p, dict) and "x" in p and "y" in p:
                    pts.append((float(p["x"]), float(p["y"])))
            if len(pts) >= 2:
                a, b = pts[0], pts[-1]
                return [f"    film.add(Route({a!r}, {b!r}, {t_in}))  # {oid}"]
        return [f"    # map graphic {oid} is environment-driven; markers are separate objects"]
    if kind == "card":
        w = obj.get("width") or 1200
        h = obj.get("height") or 800
        return [f"    film.add(Card({x}, {y}, {w}, {h}, {t_in}, title={title!r}))  # {oid}"]
    if kind == "panel":
        w = obj.get("width") or 1200
        h = obj.get("height") or 800
        return [f"    film.add(Panel({x}, {y}, {w}, {h}, {t_in}, title={title!r}))  # {oid}"]
    return [f"    # graphic {oid} kind={kind!r} recorded, no direct constructor"]


def _emit_path(spec: dict, oid: str, obj: dict) -> list[str]:
    pts = obj.get("points") or []
    def xy(p):
        if isinstance(p, dict):
            return float(p.get("x") or 0), float(p.get("y") or 0)
        return float(p[0]), float(p[1])
    if len(pts) < 2:
        return [f"    # path {oid} skipped (need two points)"]
    a, b = xy(pts[0]), xy(pts[-1])
    width = obj.get("width") or 6
    style = obj.get("style") or {}
    t_in = _entrance_expr(obj)
    if style.get("look") == "string":
        return [f"    film.add(StringLine({a}, {b}, {t_in}, width={width}, persist=True))  # {oid}"]
    return [f"    film.add(Connector({a}, {b}, {t_in}, width={width}, rgb=ctx.rgb('accent')))  # {oid}"]


def _emit_primitive(spec: dict, oid: str, obj: dict) -> list[str]:
    x, y = _xy(obj)
    size = obj.get("size") or {}
    w = float(size.get("width") or 400)
    h = float(size.get("height") or 240)
    r = float(size.get("radius") or 16)
    kind = obj.get("primitiveKind") or "rrect"
    mat = obj.get("material") or {}
    fill = mat.get("fill") or "bg"
    fill_expr = f"ctx.rgb({fill!r})" if fill in ("bg", "ink", "accent", "accent2", "muted") else "bg"
    # A tiny Item subclass would let us draw rrects; keep compiler output import-free of invented names
    # by using Panel / NoiseTexture / Connector where they already fit, else a short Item.
    ident = oid.replace("-", "_")
    if kind in ("rect", "rrect"):
        return [
            f"    class _Prim_{ident}(Item):",
            f"        def __init__(self):",
            f"            super().__init__(t_in=0.0, t_out=None, z={int(obj.get('z') or 5)}, sfx=False)",
            f"        def draw(self, c, res, t):",
            f"            c.drawRRect(rrect({x}, {y}, {w}, {h}, {r if kind == 'rrect' else 0}), paint({fill_expr}, 1))",
            f"    film.add(_Prim_{ident}())  # {oid}",
        ]
    if kind == "circle":
        return [
            f"    class _Prim_{ident}(Item):",
            f"        def __init__(self):",
            f"            super().__init__(t_in=0.0, t_out=None, z={int(obj.get('z') or 5)}, sfx=False)",
            f"        def draw(self, c, res, t):",
            f"            c.drawCircle({x}, {y}, {r or w/2}, paint({fill_expr}, 1))",
            f"    film.add(_Prim_{ident}())  # {oid}",
        ]
    if kind == "line":
        return [f"    film.add(Connector(({x}, {y}), ({x + w}, {y + h}), 0.0, rgb={fill_expr}))  # {oid}"]
    if kind in ("texture", "grain"):
        return [f"    film.add(NoiseTexture(z={int(obj.get('z') or -850)}))  # {oid}"]
    if kind == "dot_field":
        pts = obj.get("path") or [(x, y), (x + w, y), (x, y + h)]
        return [f"    film.add(DotField({list(map(tuple, pts))!r}, 0.0, 0.8))  # {oid}"]
    if kind == "path" and obj.get("path"):
        return _emit_path(spec, oid, {"points": obj["path"], "entrance": obj.get("entrance"), "style": mat, "width": w})
    return [f"    # primitive {oid} kind={kind!r}"]


def _emit_type(spec: dict, tid: str, typo: dict) -> list[str]:
    x, y = _xy(typo)
    text = (typo.get("text") or "").replace("\\", "\\\\").replace('"', '\\"')
    size = typo.get("size") or 120
    t_in = f"_anchor(ctx, {{'anchorWordId': {typo['anchorWordId']!r}}})" if typo.get("anchorWordId") else _entrance_expr(typo)
    role = typo.get("role") or "title"
    if role == "lower_third":
        return [f"    film.add(LowerThird({text!r}, '', t_in={t_in}))  # {tid}"]
    return [f"    film.add(HeroSlam({text!r}, {x}, {y}, {size}, {t_in}, None, rgb=ink))  # {tid}"]


def _emit_effect(spec: dict, oid: str, obj: dict) -> list[str]:
    kind = obj.get("effectKind")
    t = _time_expr(spec, obj)
    params = obj.get("params") or {}
    target = obj.get("targetId")
    # Resolve target position if present.
    pos = {"x": 0, "y": 0}
    if target:
        bag = (spec.get("objects") or {}).get(target) or (spec.get("typography") or {}).get(target) or {}
        pos = bag.get("position") or pos
    x, y = float(pos.get("x") or 0), float(pos.get("y") or 0)
    if kind == "spotlight":
        strength = float(params.get("strength") or 0.55)
        radius = params.get("radius")
        if radius is None:
            return [f"    film.focus({t}, {x}, {y}, 800, {strength})  # {oid}"]
        return [f"    film.focus({t}, {x}, {y}, {float(radius)}, {strength})  # {oid}"]
    if kind == "shake":
        return [f"    film.shake({t}, {float(params.get('amplitude') or 1.0)})  # {oid}"]
    if kind == "damp":
        return [f"    film.damp({t})  # {oid}"]
    if kind == "grain":
        return [f"    film.add(NoiseTexture(z=-850))  # {oid} grain"]
    if kind == "hold":
        return [f"    # camera hold is expressed via animate_camera easing='hold' ({oid})"]
    return [f"    # effect {oid} kind={kind!r}"]


def _emit_extension(spec: dict, oid: str, obj: dict) -> list[str]:
    from clips_worker.motion_studio.tools.extensions import use_component
    rec = use_component(obj.get("component") or "", obj.get("componentVersion"))
    if not rec:
        return [f"    # extension {oid}: component {obj.get('component')!r} is not registered in this process"]
    # The registered component exposes build or an Item class; we instantiate via a documented factory comment.
    return [
        f"    # extension {oid}: {rec['name']}@{rec['version']}",
        f"    # component source is registered; the sandboxed runtime binds it by name.",
    ]


def _emit_camera(spec: dict, cam: dict) -> list[str]:
    t0 = frames_to_s(spec, cam.get("startFrame") or 0)
    t1 = frames_to_s(spec, cam.get("endFrame") or cam.get("startFrame") or 0)
    a = cam.get("from") or {"x": 0, "y": 0, "zoom": 0.4, "rot": 0}
    b = cam.get("to") or a
    lines = [
        f"    film.cam({t0:.4f}, {float(a['x'])}, {float(a['y'])}, {float(a['zoom'])}, {float(a.get('rot') or 0)})  # {cam.get('id')}",
    ]
    if cam.get("easing") != "hold":
        lines.append(
            f"    film.cam({t1:.4f}, {float(b['x'])}, {float(b['y'])}, {float(b['zoom'])}, {float(b.get('rot') or 0)})"
        )
    focus = cam.get("focusTargetId")
    if focus:
        bag = (spec.get("objects") or {}).get(focus) or (spec.get("typography") or {}).get(focus) or {}
        pos = bag.get("position") or {"x": float(b["x"]), "y": float(b["y"])}
        # Place the spotlight at the end of the move, not twice in 0.25 s.
        lines.append(f"    film.focus({t1:.4f}, {float(pos.get('x') or 0)}, {float(pos.get('y') or 0)}, 800, 0.55)")
    return lines

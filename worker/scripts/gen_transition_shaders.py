"""Generate shader_selftest.json and transition-shaders.gen.ts (requires headless GL)."""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SHADER_DIR = REPO / "worker" / "clips_worker" / "shaders"
FIXTURE = REPO / "worker" / "tests" / "fixtures" / "shader_selftest.json"
OUT_TS = REPO / "new-app" / "lib" / "clips" / "editor" / "g4" / "transition-shaders.gen.ts"
NOTICE = (SHADER_DIR / "NOTICE.md").read_text(encoding="utf-8")
PIN = "b28fce3eaeaa10d2cc09fe85b4615052da02e37b"
TYPES = ("spin", "glitch", "light_leak", "zoom_blur", "whip_pan", "ripple")


def _gradient(w: int, h: int, invert: bool = False) -> bytes:
    out = bytearray(w * h * 3)
    for y in range(h):
        for x in range(w):
            i = (y * w + x) * 3
            r, g, b = (x * 8) % 256, (y * 14) % 256, (x * y) & 255
            if invert:
                r, g, b = 255 - r, 255 - g, 255 - b
            out[i : i + 3] = (r, g, b)
    return bytes(out)


def _render_frame(ctx, shader_type: str, progress: float, w: int, h: int, a: bytes, b: bytes) -> bytes:
    from clips_worker.shader_transitions import _PRELUDE_HEAD, _PRELUDE_TAIL, _VERT, program

    src = _PRELUDE_HEAD + (SHADER_DIR / f"{shader_type}.glsl").read_text(encoding="utf-8") + _PRELUDE_TAIL
    prog = ctx.program(vertex_shader=_VERT, fragment_shader=src)
    fbo = ctx.framebuffer(color_attachments=[ctx.texture((w, h), 3)])
    quad = ctx.buffer(struct.pack("8f", -1, -1, 1, -1, -1, 1, 1, 1))
    vao = ctx.vertex_array(prog, [(quad, "2f", "in_pos")])
    ta = ctx.texture((w, h), 3)
    tb = ctx.texture((w, h), 3)
    ta.write(a)
    tb.write(b)
    prog["progress"].value = progress
    prog["ratio"].value = w / h
    prog["uRes"].value = (float(w), float(h))
    ta.use(0)
    tb.use(1)
    fbo.use()
    vao.render()
    raw = bytes(fbo.read(components=3, alignment=1))
    fbo.release()
    vao.release()
    ta.release()
    tb.release()
    return raw[h - 1 :: -1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.parse_args()
    from clips_worker.shader_transitions import gl_context

    ctx, _ = gl_context()
    w, h = 160, 90
    a = _gradient(w, h, False)
    b = _gradient(w, h, True)
    selftest = {}
    for t in TYPES:
        rows = []
        for p in (0.25, 0.5, 0.75):
            raw = _render_frame(ctx, t, float(p), w, h, a, b)
            rows.append(list(raw[: min(4096, len(raw))]))
        selftest[t] = rows
    ctx.release()

    prelude = (_PRELUDE_HEAD + _PRELUDE_TAIL.split("void main")[0]).strip()
    shaders = {}
    for t in TYPES:
        body = (SHADER_DIR / f"{t}.glsl").read_text(encoding="utf-8")
        shaders[t] = {"src": body.strip(), "sha256": hashlib.sha256(body.encode()).hexdigest()}

    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps({"selftest": selftest, "pin": PIN}) + "\n")

    ts = [
        "/** Generated by worker/scripts/gen_transition_shaders.py — do not edit. */",
        f"export const GL_TRANSITIONS_PIN = '{PIN}'",
        "export const GL_TRANSITIONS_LICENSE = " + json.dumps(NOTICE) + " as const",
        "export const PRELUDE = " + json.dumps(_PRELUDE_HEAD.strip()) + " as const",
        "export const SHADERS = " + json.dumps(shaders, indent=2) + " as const",
        "export const SELFTEST: Record<string, number[][]> = " + json.dumps(selftest) + " as const",
        "export type ShaderType = keyof typeof SHADERS",
    ]
    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text("\n".join(ts) + "\n")
    print(f"wrote {FIXTURE} and {OUT_TS}")


if __name__ == "__main__":
    main()

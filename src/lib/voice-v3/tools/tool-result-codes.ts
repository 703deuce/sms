/**
 * Standard Voice V3 tool result / error codes for Astra reasoning.
 */

export const VOICE_TOOL_ERROR_CODES = {
  MISSING_REQUIRED_INFORMATION: "MISSING_REQUIRED_INFORMATION",
  INVALID_ARGUMENT: "INVALID_ARGUMENT",
  INVALID_ARGUMENTS: "INVALID_ARGUMENTS",
  INVALID_IDENTIFIER: "INVALID_IDENTIFIER",
  STALE_OPERATION: "STALE_OPERATION",
  STALE_OFFER_SET: "STALE_OFFER_SET",
  SLOT_NO_LONGER_AVAILABLE: "SLOT_NO_LONGER_AVAILABLE",
  NOT_FOUND: "NOT_FOUND",
  APPOINTMENT_NOT_FOUND: "APPOINTMENT_NOT_FOUND",
  MULTIPLE_MATCHES: "MULTIPLE_MATCHES",
  CONFIRMATION_REQUIRED: "CONFIRMATION_REQUIRED",
  CANCELLATION_CONFIRMATION_REQUIRED: "CANCELLATION_CONFIRMATION_REQUIRED",
  PROVIDER_UNAVAILABLE: "PROVIDER_UNAVAILABLE",
  PROVIDER_TIMEOUT: "PROVIDER_TIMEOUT",
  OUTCOME_UNKNOWN: "OUTCOME_UNKNOWN",
  UNAUTHORIZED_OPERATION: "UNAUTHORIZED_OPERATION",
  CALL_ENDED: "CALL_ENDED",
  INTERNAL_ERROR: "INTERNAL_ERROR",
  UNKNOWN_TOOL: "UNKNOWN_TOOL",
  TOOL_EXECUTION_FAILED: "TOOL_EXECUTION_FAILED",
} as const;

export type VoiceToolErrorCode =
  (typeof VOICE_TOOL_ERROR_CODES)[keyof typeof VOICE_TOOL_ERROR_CODES];

/** Whether Astra may reasonably retry after this code (application policy). */
export function isRetryableToolErrorCode(code: string): boolean {
  switch (code) {
    case VOICE_TOOL_ERROR_CODES.PROVIDER_TIMEOUT:
    case VOICE_TOOL_ERROR_CODES.PROVIDER_UNAVAILABLE:
      return true;
    default:
      return false;
  }
}

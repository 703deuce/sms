export function mergeRealtorConversations(live: Conversation[]): Conversation[] {
  const liveContactIds = new Set(live.map((c) => c.contactId));
  const extras = REALTOR_CONVERSATION_FIXTURES.filter((f) => !liveContactIds.has(f.contactId));
  return [...live, ...extras].sort(
    (a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime(),
  );
}

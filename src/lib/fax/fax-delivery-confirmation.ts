import "server-only";

import { getFaxTransmission } from "./fax-service";
import { faxDisplayStatusLabel, mapToFaxDisplayStatus } from "./fax-status";
import { readPageAccounting } from "./fax-pages";

export async function buildFaxDeliveryConfirmation(
  workspaceId: string,
  transmissionId: string,
): Promise<{ text: string; canDownload: boolean }> {
  const fax = await getFaxTransmission(workspaceId, transmissionId);
  if (!fax) throw new Error("FAX_NOT_FOUND");

  const displayStatus = mapToFaxDisplayStatus({
    status: fax.status,
    direction: fax.direction,
  });
  const pages = readPageAccounting(fax.metadataJson) || {
    documentPages: fax.pageCount || 0,
    billablePages: fax.pageCount || 0,
    providerCostCents: 0,
  };

  const lines = [
    "TRANSOVO FAX DELIVERY CONFIRMATION",
    "================================",
    "",
    `Status: ${faxDisplayStatusLabel(displayStatus)}`,
    `Direction: ${fax.direction}`,
    `From: ${fax.fromE164 || "—"}`,
    `To: ${fax.toE164 || "—"}`,
    fax.recipientName ? `Recipient: ${fax.recipientName}` : "",
    "",
    `Submitted: ${fax.sentAt?.toISOString() || fax.createdAt.toISOString()}`,
    fax.deliveredAt ? `Delivered: ${fax.deliveredAt.toISOString()}` : "",
    fax.receivedAt ? `Received: ${fax.receivedAt.toISOString()}` : "",
    "",
    `Document pages: ${pages.documentPages}`,
    `Billable pages: ${pages.billablePages}`,
    "",
    fax.telnyxFaxId ? `Transmission ID: ${fax.telnyxFaxId}` : "",
    `Transovo Fax ID: ${fax.id}`,
    "",
    fax.failureReason ? `Failure reason: ${fax.failureReason}` : "",
    "",
    "This confirmation is generated by Transovo for your business records.",
    "Delivery is confirmed only when status shows Delivered or Received.",
  ].filter(Boolean);

  const canDownload = displayStatus === "delivered" || displayStatus === "received";
  return { text: lines.join("\n"), canDownload };
}
